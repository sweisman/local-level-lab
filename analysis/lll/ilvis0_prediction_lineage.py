"""Metadata guard for the fixed dense-prediction qualification inputs.

This checks assumption lineage, not inequality arithmetic, native enclosures,
covariance validity or empirical coverage. Those retain their separate gates.
Only receipts regenerated by register may authorize a data-conditioned parent.
No numerical libraries, packet integration, optimization or observations from
the withheld period are needed here. Active/frozen studies are never changed.
"""
from dataclasses import dataclass
from fractions import Fraction as F
import math
from .ilvis0_conditioned_acceleration import _digest as _id


def _vector(value,n):
    return (isinstance(value,(list,tuple)) and len(value)==n
        and all(type(v) in (int,float) and math.isfinite(v) for v in value))


def _matrix(value,n,m):
    return isinstance(value,(list,tuple)) and len(value)==n and all(_vector(v,m) for v in value)


def _family(errors,weights,times):
    """Bind the exact signed rows to the existing 453-error family."""
    future=list(map(float,range(292,439)));law=errors['law'];allowance=errors['allowances']
    row_ids=[f'training:legendre-{j}:{axis}' for j in range(4) for axis in ('north','east','up')]
    row_ids += [f'future:{t}:{axis}' for t in future for axis in ('north','east','up')]
    if (times!=list(map(float,range(2,291))) or law['times_s']!=times+future
            or law['clock_interval_s']!=['-1','1'] or law['origin_s']!='0'
            or errors['future_observations_used'] is not False
            or errors['scalar_family_count']!=453 or errors['training_epochs']!=289
            or errors['summary_rows']!=12 or errors['future_epochs']!=147
            or allowance['supported'] is not True or allowance['coordinate_count']!=453
            or allowance['row_ids']!=row_ids or not _vector(allowance['radius_m'],453)
            or any(v<0 for v in allowance['radius_m']) or not _matrix(weights,12,3*len(times))):
        raise ValueError('complete fixed training/future error family required')
    covariance=_id(law)
    projection=dict(version='ilvis0-fixed-linear-variance-v1',covariance_id=covariance,
        weights=[[str(F(float(v))) for v in row]+['0']*(3*len(future)) for row in weights])
    family=dict(summary_projection_id=_id(projection),future_times_s=future,
        covariance_id=covariance,row_ids=row_ids)
    family_id=_id(family)
    if (errors['covariance_id']!=covariance or allowance['covariance_id']!=covariance
            or errors['summary_projection_id']!=_id(projection)
            or errors['family_projection_id']!=family_id or allowance['projection_id']!=family_id):
        raise ValueError('signed weights, covariance or error-family identity changed')
    # The covariance/projection identity does not include alpha, scale or the
    # selected radii. Bind the complete allowance certificate as well: a tighter
    # earlier event cannot be inherited under a looser, differently budgeted one.
    premise_id=_id(dict(family_projection_id=family_id,allowances=allowance))
    return family_id,premise_id


@dataclass(frozen=True,init=False)
class Origin:
    input_binding:str
    family_id:str
    error_premise_id:str
    frame_id:str
    observations_id:str
    parents:tuple
    lower:tuple
    upper:tuple
    design:tuple
    upper_bounds:tuple

    def report(self):
        return dict(version='ilvis0-dense-conditioning-lineage-v1',input_binding=self.input_binding,
            family_id=self.family_id,frame_id=self.frame_id,observations_id=self.observations_id,
            error_premise_id=self.error_premise_id,
            parents=list(self.parents),inequality_rows=len(self.design),physical_parameter_count=27,
            parameter_count=51,premise_lineage_checked=True,native_bounds_qualified=False,
            prediction_method_qualified=False,observational_coverage_qualified=False,scientific_decision='abstain')


def register(training,reports,rows,errors,bundle,*,origins=()):
    """Issue a typed origin after checking the exact conditioning premises.

    Call after the separately qualified row builder. Existing parent constraints
    must be retained, in input-binding order, before the new projected rows.
    This prevents an enclosure valid only within an earlier region from being
    applied outside that region. It also prevents importing old one-metre
    constraints into a different error family or observation realization.
    """
    try:return _register(training,reports,rows,errors,bundle,origins)
    except (KeyError,TypeError,AttributeError,OverflowError) as error:
        raise ValueError('complete conditioning-lineage metadata required') from error


def _register(training,reports,rows,errors,bundle,origins):
    source=training['source_binding'];region=training['region'];times=training['times_s'];binding=rows['binding']
    family_id,error_premise_id=_family(errors,binding['weights'],times)
    if (set(source)!={'source_id','reference_binding','normalized_center','lower','upper'}
            or not all(isinstance(source[k],str) and source[k] for k in ('source_id','reference_binding'))
            or any(not _vector(source[k],27) for k in ('normalized_center','lower','upper'))
            or region['parameter_count']!=51 or rows['parameter_count']!=51
            or rows['physical_parameter_count']!=27 or rows['original_expression_columns']!=51
            or rows['new_rows']!=24 or rows['future_observations_used'] is not False
            or rows['observation_allowance_m']!=errors['allowances']['radius_m'][:12]
            or binding['source']!=source or binding['times_s']!=times
            or binding['coordinate_scale']!=region['coordinate_scale']
            or binding['expression_columns']!=51 or binding['physical_parameter_count']!=27
            or binding['enclosure_parameter_count']!=51 or rows['projected_training_id']!=_id(binding)
            or not _matrix(rows['design'],24,51) or not _vector(rows['upper'],24)
            or any(not _vector(region[k],51) for k in ('lower','upper','center'))
            or not _matrix(region['design'],3*len(times),51)
            or not _matrix(training['observations'],len(times),3)
            or not _matrix(training['nominal'],len(times),3) or len(reports)!=len(times)):
        raise ValueError('matching complete source, native rows and error radii required')
    if (any(not a<=c<=b for a,c,b in zip(region['lower'],region['center'],region['upper'],strict=True))
            or region['center'][:27]!=source['normalized_center']
            or any(not a<=b<=c<=d for a,b,c,d in zip(source['lower'],region['lower'][:27],
                region['upper'][:27],source['upper'],strict=True))):
        raise ValueError('complete physical/source domain required')
    frame_id=_id(dict(source_id=source['source_id'],reference_binding=source['reference_binding'],
        normalized_center=source['normalized_center'],coordinate_scale=region['coordinate_scale']))
    observations_id=_id(dict(frame_id=frame_id,times_s=times,observations=training['observations']))
    known={}
    for origin in origins:
        if not isinstance(origin,Origin) or origin.input_binding in known:
            raise ValueError('unique typed origins regenerated from their inputs required')
        known[origin.input_binding]=origin
    input_binding=_id(bundle)
    if input_binding in known:raise ValueError('duplicate or circular conditioning lineage')
    used=set()
    for i,report in enumerate(reports):
        if (any(report.get(k)!=v for k,v in source.items()) or report['time_s']!=times[i]
                or report['center']!=training['nominal'][i] or not _vector(report['unshared_remainder'],3)
                or any(v<0 for v in report['unshared_remainder'])):
            raise ValueError('native source, frame, time or center changed')
        premise=report['conditioning']
        if premise['source_id']!=source['source_id'] or premise['reference_binding']!=source['reference_binding']:
            raise ValueError('conditioning source or frame changed')
        if premise['version']=='ilvis0-physical-directional-acceleration-v1':
            if (premise['uses_training_data'] is not False or premise['applies_only_to_physical_domain'] is not True
                    or premise['lower']!=source['lower'] or premise['upper']!=source['upper']):
                raise ValueError('unconditional physical-domain root required')
        elif premise['version']=='ilvis0-verified-training-acceleration-v1':
            key=premise['input_binding']
            if key not in known:raise ValueError('unknown training premise; old conditioning cannot be relabeled')
            origin=known[key]
            if origin.family_id!=family_id or origin.error_premise_id!=error_premise_id:
                raise ValueError('parent uses a different error family or allowance premise')
            if origin.frame_id!=frame_id or origin.observations_id!=observations_id:
                raise ValueError('parent source/frame/observations changed')
            if (tuple(source['lower'])!=origin.lower[:27] or tuple(source['upper'])!=origin.upper[:27]
                    or any(not a<=b<=c<=d for a,b,c,d in zip(origin.lower,region['lower'],
                        region['upper'],origin.upper,strict=True))):
                raise ValueError('new rows leave the parent proof domain')
            used.add(key)
        else:raise ValueError('unsupported conditioning origin')
    expression=dict(nominal=training['nominal'],observations=training['observations'],design=region['design'],
        unshared_remainders=[r['unshared_remainder'] for r in reports],arithmetic_allowance=region['arithmetic_allowance'],
        lower=region['lower'],upper=region['upper'],center=region['center'])
    if binding['expression_sha256']!=_id(expression):raise ValueError('projected native expression or observations changed')
    problem=bundle['training']['region'];parents=tuple(sorted(used));expected_rows=[];expected_upper=[]
    for key in parents:
        expected_rows.extend(map(list,known[key].design));expected_upper.extend(known[key].upper_bounds)
    expected_rows.extend(rows['design']);expected_upper.extend(rows['upper'])
    if problem['inequality_design']!=expected_rows or problem['inequality_upper']!=expected_upper:
        raise ValueError('parent constraints or current projected inequalities changed')
    if (any(problem.get(k)!=region[k] for k in ('parameter_count','lower','upper','center',
                'coordinate_scale','arithmetic_allowance','design'))
            or problem['binding']!=source['reference_binding'] or problem['source_id']!=source['source_id']
            or problem['future_truth_used'] is not False
            or bundle['reference']['binding']!=source['reference_binding']
            or bundle['reference']['parent']['source_id']!=source['source_id']
            or not _vector(bundle['lower'],51) or not _vector(bundle['upper'],51)
            or any(not a<=b<=c<=d for a,b,c,d in zip(region['lower'],bundle['lower'],
                bundle['upper'],region['upper'],strict=True))):
        raise ValueError('conditioning bundle changed its source or full physical domain')
    origin=object.__new__(Origin)
    fields=dict(input_binding=input_binding,family_id=family_id,error_premise_id=error_premise_id,
        frame_id=frame_id,observations_id=observations_id,
        parents=parents,lower=tuple(bundle['lower']),upper=tuple(bundle['upper']),
        design=tuple(tuple(row) for row in expected_rows),upper_bounds=tuple(expected_upper))
    for key,value in fields.items():object.__setattr__(origin,key,value)
    return origin
